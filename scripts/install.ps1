function Invoke-NativeProcess {
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [string[]]$ArgumentList = @(),
        [string]$WorkDir = "",
        [string]$FailMessage = "",
        [switch]$CaptureOutput
    )
    # PS 5.1: native stderr becomes a terminating error when ErrorActionPreference=Stop.
    # Splatting arrays that start with "-m" also looks like a named parameter.
    $oldEap = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $code = 0
    $output = $null
    try {
        if ($WorkDir) {
            Push-Location -LiteralPath $WorkDir
        }
        try {
            if ($CaptureOutput) {
                $output = & $FilePath @ArgumentList
            }
            else {
                # Write-Host so native stdout does not pollute function return values.
                & $FilePath @ArgumentList | ForEach-Object { Write-Host $_ }
            }
            $code = $LASTEXITCODE
        }
        finally {
            if ($WorkDir) {
                Pop-Location
            }
        }
    }
    finally {
        $ErrorActionPreference = $oldEap
    }
    if ($code -ne 0) {
        if ([string]::IsNullOrWhiteSpace($FailMessage)) {
            $FailMessage = "$FilePath $($ArgumentList -join ' ') failed (exit $code)"
        }
        throw $FailMessage
    }
    if ($CaptureOutput) {
        return $output
    }
}

function Invoke-Python {
    param(
        [Parameter(Mandatory = $true)][string[]]$PythonCmd,
        [Parameter(Mandatory = $true)][string[]]$PythonArgs,
        [string]$WorkDir = ""
    )
    if ($null -eq $PythonCmd -or $PythonCmd.Count -eq 0) {
        throw "PythonCmd is empty"
    }
    $exe = $PythonCmd[0]
    $all = @()
    if ($PythonCmd.Count -gt 1) {
        $all += $PythonCmd[1..($PythonCmd.Count - 1)]
    }
    $all += $PythonArgs
    Invoke-NativeProcess -FilePath $exe -ArgumentList $all -WorkDir $WorkDir
}

function Find-OscriptPath {
    $fromPath = Get-CommandPath "oscript"
    if ($fromPath) {
        return $fromPath
    }
    $candidates = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($env:OVM_INSTALL_PATH)) {
        $candidates.Add((Join-Path $env:OVM_INSTALL_PATH "current\bin\oscript.exe"))
        $candidates.Add((Join-Path $env:OVM_INSTALL_PATH "current\bin\oscript"))
    }
    if (-not [string]::IsNullOrWhiteSpace($env:LOCALAPPDATA)) {
        $candidates.Add((Join-Path $env:LOCALAPPDATA "ovm\current\bin\oscript.exe"))
    }
    if (-not [string]::IsNullOrWhiteSpace($env:USERPROFILE)) {
        $candidates.Add((Join-Path $env:USERPROFILE "ovm\current\bin\oscript.exe"))
    }
    foreach ($c in $candidates) {
        if ($c -and (Test-Path -LiteralPath $c -PathType Leaf)) {
            return (Resolve-Path -LiteralPath $c).Path
        }
    }
    return ""
}

function Ensure-Oscript {
    Write-Step "OneScript (ovm)"
    $existing = Find-OscriptPath
    if ($existing) {
        $binDir = Split-Path -Parent $existing
        if ($env:Path -notlike ("*{0}*" -f $binDir)) {
            $env:Path = "$binDir;$env:Path"
        }
        Write-Host "OK  oscript ($existing)"
        return $existing
    }

    Write-Host "oscript не найден в PATH."
    Write-Host "Установим OneScript через OVM: https://github.com/oscript-library/ovm"
    Write-Host "Версия: $OscriptVersion (нужен .NET Framework 4.8+ для ovm.exe на Windows)."
    if (-not $NonInteractive) {
        $ans = Read-Prompt "Подтверждение: установить OneScript ($OscriptVersion) через ovm? [Y/n]"
        if ($ans -match '^(?i)(n|no|н|нет)$') {
            throw "oscript required. Install via OVM (docs/prerequisites.md) or re-run and accept install."
        }
    }
    else {
        Write-Host "NonInteractive: installing OneScript via ovm ($OscriptVersion)..."
    }

    $ovmDir = Join-Path $ToolsDir "ovm"
    New-Item -ItemType Directory -Force -Path $ovmDir | Out-Null
    $ovmExe = Join-Path $ovmDir "ovm.exe"
    if (-not (Test-Path -LiteralPath $ovmExe -PathType Leaf)) {
        $asset = Get-GithubReleaseAsset "oscript-library/ovm" "ovm.exe"
        Save-RemoteFile -Uri $asset.browser_download_url -OutFile $ovmExe -Activity "ovm"
    }

    Invoke-NativeProcess -FilePath $ovmExe -ArgumentList @("install", $OscriptVersion) -FailMessage "ovm install $OscriptVersion failed"
    Invoke-NativeProcess -FilePath $ovmExe -ArgumentList @("use", $OscriptVersion) -FailMessage "ovm use $OscriptVersion failed"

    $existing = Find-OscriptPath
    if (-not $existing) {
        throw "oscript still not found after ovm install/use. Check OVM_INSTALL_PATH or open a new shell. docs/prerequisites.md"
    }
    $binDir = Split-Path -Parent $existing
    $env:Path = "$binDir;$env:Path"
    Write-Host "OK  oscript ($existing) via ovm"
    Write-Host "Hint: add to user PATH for new shells: $binDir"
    return $existing
}

function Get-GithubReleaseAsset([string]$Repo, [string]$NameMatch) {
    $rel = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repo/releases/latest" -Headers $GithubHeaders
    $asset = $rel.assets | Where-Object { $_.name -like $NameMatch } | Select-Object -First 1
    if ($null -eq $asset) {
        throw "No GitHub asset matching '$NameMatch' in $Repo latest release"
    }
    return $asset
}

function Save-RemoteFile {
    param(
        [Parameter(Mandatory = $true)][string]$Uri,
        [Parameter(Mandatory = $true)][string]$OutFile,
        [string]$Activity = "Downloading"
    )
    Write-Host "Downloading $Uri"
    $curl = Get-CommandPath "curl.exe"
    if ($curl) {
        $oldEap = $ErrorActionPreference
        $ErrorActionPreference = "Continue"
        try {
            & $curl -fL --progress-bar -A "kuibysheff-1c-live-install" -o $OutFile $Uri
            if ($LASTEXITCODE -ne 0) {
                throw "curl download failed (exit $LASTEXITCODE): $Uri"
            }
        }
        finally {
            $ErrorActionPreference = $oldEap
        }
        return
    }
    Write-Host "(curl.exe not found; download without progress bar: $Activity)"
    $oldEap = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        Invoke-WebRequest -Uri $Uri -OutFile $OutFile -Headers $GithubHeaders -UseBasicParsing
    }
    finally {
        $ErrorActionPreference = $oldEap
    }
}

function Expand-ZipTo([string]$ZipPath, [string]$Dest) {
    New-Item -ItemType Directory -Force -Path $Dest | Out-Null
    Expand-Archive -LiteralPath $ZipPath -DestinationPath $Dest -Force
}

function Find-FileUnder([string]$Root, [string]$FileName) {
    $hit = Get-ChildItem -LiteralPath $Root -Recurse -File -Filter $FileName -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -eq $hit) {
        return ""
    }
    return $hit.FullName
}

function Install-KbshffFromRelease {
    $stable = Join-Path $ToolsDir "kbshff.exe"
    $asset = Get-GithubReleaseAsset "gazalievtimur/Agent-Kuibysheff" "agent_Kuibysheff-*-x86_64-pc-windows-msvc.zip"
    $zip = Join-Path $env:TEMP "kbshff-windows-msvc.zip"
    $extract = Join-Path $env:TEMP "kbshff-windows-msvc-extract"
    if (Test-Path -LiteralPath $extract) {
        Remove-Item -LiteralPath $extract -Recurse -Force
    }
    Save-RemoteFile -Uri $asset.browser_download_url -OutFile $zip -Activity "kbshff release"
    $shaAsset = $null
    try {
        $shaAsset = Get-GithubReleaseAsset "gazalievtimur/Agent-Kuibysheff" "agent_Kuibysheff-*-x86_64-pc-windows-msvc.zip.sha256"
    }
    catch {
        Write-Warning "No .sha256 asset for kbshff release; skipping checksum"
    }
    if ($shaAsset) {
        $shaFile = Join-Path $env:TEMP "kbshff-windows-msvc.zip.sha256"
        Save-RemoteFile -Uri $shaAsset.browser_download_url -OutFile $shaFile -Activity "kbshff checksum"
        $expected = ((Get-Content -LiteralPath $shaFile -Raw) -split '\s+')[0].Trim().ToLowerInvariant()
        $actual = (Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($expected -and $expected -ne $actual) {
            throw "kbshff zip SHA256 mismatch (expected $expected, got $actual)"
        }
        Write-Host "OK  kbshff SHA256"
    }
    Expand-ZipTo $zip $extract
    $found = Find-FileUnder $extract "kbshff.exe"
    if (-not $found) {
        throw "kbshff.exe not found in release archive"
    }
    New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
    Copy-Item -LiteralPath $found -Destination $stable -Force
    Write-Host "Installed kbshff -> $stable"
    return (Resolve-Path $stable).Path
}

function Ensure-Kbshff([hashtable]$EnvMap) {
    Write-Step "kbshff"
    $explicit = Get-EnvOrMap $EnvMap "KBSHFF_BIN"
    if ($explicit -and (Test-Path -LiteralPath $explicit -PathType Leaf)) {
        return (Resolve-Path -LiteralPath $explicit).Path
    }
    $vendored = Join-Path $ToolsDir "kbshff.exe"
    if (Test-Path -LiteralPath $vendored -PathType Leaf) {
        return (Resolve-Path $vendored).Path
    }
    $fromPath = Get-CommandPath "kbshff"
    if ($fromPath) {
        return $fromPath
    }
    $parent = Split-Path -Parent $RepoRoot
    $src = Get-EnvOrMap $EnvMap "KUIBYSHEFF_SRC"
    $candidates = @()
    if ($src) { $candidates += $src }
    $candidates += @(
        (Join-Path $parent "Agent-Kuibysheff"),
        (Join-Path $parent "Agent Kuibyshev")
    )
    $foundSrc = ""
    foreach ($c in $candidates) {
        if (Test-Path -LiteralPath (Join-Path $c "Cargo.toml") -PathType Leaf) {
            $foundSrc = (Resolve-Path -LiteralPath $c).Path
            $releaseExe = Join-Path $foundSrc "target\release\kbshff.exe"
            $releaseBin = Join-Path $foundSrc "target\release\kbshff"
            if (Test-Path -LiteralPath $releaseExe) { return (Resolve-Path $releaseExe).Path }
            if (Test-Path -LiteralPath $releaseBin) { return (Resolve-Path $releaseBin).Path }
            break
        }
    }
    try {
        return Install-KbshffFromRelease
    }
    catch {
        Write-Warning "GitHub release download failed: $($_.Exception.Message)"
    }
    if (-not $foundSrc) {
        if (-not (Test-Command "git")) {
            throw "kbshff not found and git is missing. Install kbshff or clone https://github.com/gazalievtimur/Agent-Kuibysheff"
        }
        if (-not (Test-Command "cargo")) {
            throw "kbshff not found. Put it on PATH, set KBSHFF_BIN, or install Rust (cargo) to build from source. See https://github.com/gazalievtimur/Agent-Kuibysheff"
        }
        $foundSrc = Join-Path $parent "Agent-Kuibysheff"
        Write-Host "Cloning Agent-Kuibysheff -> $foundSrc"
        Invoke-NativeProcess -FilePath "git" -ArgumentList @("clone", "--depth", "1", "https://github.com/gazalievtimur/Agent-Kuibysheff.git", $foundSrc) -FailMessage "git clone Agent-Kuibysheff failed"
    }
    $releaseExe = Join-Path $foundSrc "target\release\kbshff.exe"
    $releaseBin = Join-Path $foundSrc "target\release\kbshff"
    if (Test-Path -LiteralPath $releaseExe) { return (Resolve-Path $releaseExe).Path }
    if (Test-Path -LiteralPath $releaseBin) { return (Resolve-Path $releaseBin).Path }
    if (-not (Test-Command "cargo")) {
        throw "cargo not found (needed to build kbshff from $foundSrc)"
    }
    Write-Host "Building kbshff from $foundSrc"
    Invoke-NativeProcess -FilePath "cargo" -ArgumentList @("build", "--release", "-p", "agent_Kuibysheff", "--bin", "kbshff") -WorkDir $foundSrc -FailMessage "cargo build kbshff failed"
    if (Test-Path -LiteralPath $releaseExe) { return (Resolve-Path $releaseExe).Path }
    if (Test-Path -LiteralPath $releaseBin) { return (Resolve-Path $releaseBin).Path }
    throw "kbshff binary missing after cargo build under $foundSrc"
}

