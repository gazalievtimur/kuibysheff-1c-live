function Invoke-KbshffProvider([string]$Kbshff, [string]$ProjectRoot, [string]$AgentId, [string[]]$ExpectedSkills, [string]$ProvBaseUrl, [string]$ProvModel, [string]$ProvKeyEnv, [string]$StepLabel = "") {
    $title = "kbshff CLI: init / import skills / provider set / check ($AgentId)"
    if ($StepLabel) {
        $title = "$StepLabel $title"
    }
    Write-Step $title
    New-Item -ItemType Directory -Force -Path $ProjectRoot | Out-Null
    Invoke-NativeProcess -FilePath $Kbshff -ArgumentList @("init", $AgentId, "--project-root", $ProjectRoot, "--force") -FailMessage "kbshff init $AgentId failed"
    $staging = Join-Path $ProjectRoot ".kuibysheff\.1c-live-import\$AgentId"
    if (Test-Path -LiteralPath $staging) {
        Remove-Item -LiteralPath $staging -Recurse -Force
    }
    New-Item -ItemType Directory -Force -Path $staging | Out-Null
    $settings = Join-Path $RepoRoot "profiles\$AgentId"
    foreach ($name in @("master_prompt.md", "skills.dsl", "rules.md")) {
        $src = Join-Path $settings $name
        if (-not (Test-Path -LiteralPath $src -PathType Leaf)) {
            throw "missing $src - conveyor profile $AgentId is incomplete"
        }
        Copy-Item -LiteralPath $src -Destination (Join-Path $staging $name) -Force
    }
    Invoke-NativeProcess -FilePath $Kbshff -ArgumentList @("config", "--project-root", $ProjectRoot, "--agent", $AgentId, "import", "--from", $staging, "--force") -FailMessage "kbshff config import $AgentId failed"
    Invoke-NativeProcess -FilePath $Kbshff -ArgumentList @("config", "--project-root", $ProjectRoot, "--agent", $AgentId, "provider", "set", "--base-url", $ProvBaseUrl, "--model", $ProvModel, "--api-key-env", $ProvKeyEnv) -FailMessage "kbshff config provider set $AgentId failed"
    $listed = Invoke-NativeProcess -FilePath $Kbshff -ArgumentList @("config", "--project-root", $ProjectRoot, "--agent", $AgentId, "--format", "json", "skill", "list") -FailMessage "kbshff config skill list $AgentId failed" -CaptureOutput
    $listedText = ($listed | Out-String)
    foreach ($skill in $ExpectedSkills) {
        if ($listedText -notmatch [regex]::Escape($skill)) {
            throw "skill '$skill' missing after import of $AgentId. skill list: $listedText"
        }
    }
    Write-Host "OK  $AgentId skills: $($ExpectedSkills -join ', ')"
    Invoke-NativeProcess -FilePath $Kbshff -ArgumentList @("check", "--project-root", $ProjectRoot, "--agent", $AgentId, "--skip-mcp", "--skip-sandbox") -FailMessage "kbshff check $AgentId failed"
}

function Install-ConveyorProfiles([string]$Kbshff, [string]$ProjectRoot, [string]$ProvBaseUrl, [hashtable]$ProvModels, [string]$ProvKeyEnv) {
    Write-Step "Conveyor profiles (all skills)"
    $agents = Get-ConveyorAgents
    $total = $agents.Count
    $i = 0
    foreach ($agent in $agents) {
        $i++
        $model = [string]$ProvModels[$agent.Id]
        if ([string]::IsNullOrWhiteSpace($model)) {
            throw "model for agent $($agent.Id) is empty"
        }
        Invoke-KbshffProvider $Kbshff $ProjectRoot $agent.Id $agent.Skills $ProvBaseUrl $model $ProvKeyEnv "[$i/$total]"
    }
}

function Read-ProviderSettings([hashtable]$EnvMap) {
    Write-Step "AI provider"
    if (-not $NonInteractive) {
        Write-Host ""
        Write-Host "Нужен любой OpenAI-compatible HTTP API (Chat Completions)."
        Write-Host "Эндпоинт (base_url) и ключ - общие; модель задаётся отдельно для каждого агента конвейера."
        Write-Host "Параметры попадут в kbshff через: config provider set --base-url --model --api-key-env"
        Write-Host "Сам ключ хранится только в .env / окружении и НЕ передаётся в argv CLI."
        Write-Host "Значения по умолчанию - плейсхолдеры формата, не рекомендация конкретного вендора."
        Write-Host ""
    }
    if (-not $script:BaseUrl) {
        $script:BaseUrl = Get-EnvOrMap $EnvMap "KBSHFF_PROVIDER_BASE_URL"
        if (-not $script:BaseUrl) { $script:BaseUrl = "https://api.openai.com/v1" }
        Write-Hint "base_url - общий URL эндпоинта до /v1 для всех агентов."
        Write-Hint "Пример формата: https://api.example.com/v1"
        $script:BaseUrl = Read-Default "URL эндпоинта (base_url)" $script:BaseUrl
    }
    $pastedApiKey = ""
    if (-not $script:ApiKeyEnvName) {
        $script:ApiKeyEnvName = Get-EnvOrMap $EnvMap "KBSHFF_PROVIDER_API_KEY_ENV"
        if (-not $script:ApiKeyEnvName) { $script:ApiKeyEnvName = "OPENAI_API_KEY" }
        Write-Hint ""
        Write-Hint "Имя переменной окружения для API-ключа (не сам ключ)."
        Write-Hint "Пример: OPENAI_API_KEY. Сам ключ спросим следующим шагом (ввод скрыт)."
        Write-Hint "kbshff читает секрет из env с этим именем."
        $rawEnvName = Read-Default "Имя переменной для API-ключа" $script:ApiKeyEnvName
        if (Test-LooksLikeApiKey $rawEnvName) {
            Write-Warning "Похоже, вы вставили сам API-ключ вместо имени переменной. Ключ сохраним как секрет; имя env = OPENAI_API_KEY."
            $pastedApiKey = $rawEnvName
            $script:ApiKeyEnvName = "OPENAI_API_KEY"
            $script:ApiKeyEnvName = Read-Default "Имя переменной для API-ключа" $script:ApiKeyEnvName
        }
        else {
            $script:ApiKeyEnvName = $rawEnvName
        }
        if (-not (Test-ValidEnvVarName $script:ApiKeyEnvName)) {
            throw "Invalid API key env var name '$($script:ApiKeyEnvName)'. Use something like OPENAI_API_KEY (letters, digits, underscore)."
        }
    }
    $apiKey = $pastedApiKey
    if (-not $apiKey) {
        $apiKey = Get-EnvOrMap $EnvMap $script:ApiKeyEnvName
    }
    if (-not $apiKey) {
        $apiKey = [Environment]::GetEnvironmentVariable($script:ApiKeyEnvName, "Process")
    }
    if (-not $apiKey) {
        Write-Hint ""
        Write-Hint "Значение ключа для переменной $($script:ApiKeyEnvName)."
        Write-Hint "Ввод скрыт (символы не видны). Вставьте ключ и нажмите Enter."
        for ($attempt = 1; $attempt -le 3; $attempt++) {
            $apiKey = Read-Secret "Значение API-ключа ($($script:ApiKeyEnvName))"
            if (-not [string]::IsNullOrWhiteSpace($apiKey)) {
                break
            }
            Write-Warning "Пустой ввод (попытка $attempt/3). Вставьте ключ ещё раз - символы не отображаются."
        }
    }
    if ([string]::IsNullOrWhiteSpace($apiKey)) {
        throw "API key for $($script:ApiKeyEnvName) is required (set env, .env, or enter it interactively)"
    }
    [Environment]::SetEnvironmentVariable($script:ApiKeyEnvName, $apiKey, "Process")

    $defaultModel = $script:Model
    if (-not $defaultModel) {
        $defaultModel = Get-EnvOrMap $EnvMap "KBSHFF_PROVIDER_MODEL"
    }
    if (-not $defaultModel) {
        $defaultModel = "gpt-4o"
    }
    $script:Model = $defaultModel

    $cliByAgent = @{
        "1c-analyst"     = $script:ModelAnalyst
        "1c-yaxunit"     = $script:ModelYaxunit
        "1c-coder"       = $script:ModelCoder
        "1c-implementer" = $script:ModelImplementer
    }
    Write-Hint ""
    Write-Hint "model - id модели у провайдера. Один эндпоинт, но модель можно выбрать разной для каждой стадии."
    Write-Hint "Плейсхолдер формата: gpt-4o (Enter - принять значение в скобках)."
    $script:AgentModels = @{}
    foreach ($agent in (Get-ConveyorAgents)) {
        $envName = Get-AgentModelEnvName $agent.Id
        $chosen = [string]$cliByAgent[$agent.Id]
        if (-not $chosen) {
            $chosen = Get-EnvOrMap $EnvMap $envName
        }
        if (-not $chosen) {
            $chosen = $defaultModel
        }
        $chosen = Read-Default "Модель для $($agent.Id)" $chosen
        if ([string]::IsNullOrWhiteSpace($chosen)) {
            throw "model for $($agent.Id) is required"
        }
        $script:AgentModels[$agent.Id] = $chosen
    }
    return $apiKey
}

