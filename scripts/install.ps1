function Find-1cPlatformBins {
    $bins = New-Object System.Collections.Generic.List[string]
    $roots = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($env:ProgramFiles)) {
        $roots.Add((Join-Path $env:ProgramFiles "1cv8"))
    }
    $pf86 = ${env:ProgramFiles(x86)}
    if (-not [string]::IsNullOrWhiteSpace($pf86)) {
        $roots.Add((Join-Path $pf86 "1cv8"))
    }
    foreach ($root in $roots) {
        if (-not (Test-Path -LiteralPath $root -PathType Container)) {
            continue
        }
        Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -like "8.3.*" } |
            ForEach-Object {
                $bin = Join-Path $_.FullName "bin"
                if (-not (Test-Path -LiteralPath $bin -PathType Container)) {
                    return
                }
                $has = (Test-Path -LiteralPath (Join-Path $bin "1cv8.exe")) -or (Test-Path -LiteralPath (Join-Path $bin "ibcmd.exe"))
                if ($has) {
                    $bins.Add((Resolve-Path -LiteralPath $bin).Path)
                }
            }
    }
    return @($bins | Sort-Object -Descending)
}

function Select-PlatformBinForIngest {
    if ($PlatformPath) {
        return $PlatformPath
    }
    if ($NonInteractive) {
        return ""
    }
    Write-Hint ""
    Write-Hint "Ingest строит индекс справки платформы для MCP sntx_sem (поиск синтаксиса/справки на live-прогоне)."
    Write-Hint "Нужен каталог bin вашей лицензионной платформы 1С (обычно ...\1cv8\8.3.xx\bin)."
    Write-Hint "HBK в репозиторий не копируется."
    $found = @(Find-1cPlatformBins)
    if ($found.Count -eq 0) {
        Write-Hint "Установленные 8.3.*\bin не найдены автоматически."
        $answer = Read-Default "Путь к bin платформы 1С (пусто = пропуск)" ""
        return $answer
    }
    Write-Host "Найдены каталоги bin платформы:"
    for ($i = 0; $i -lt $found.Count; $i++) {
        Write-Host ("  [{0}] {1}" -f ($i + 1), $found[$i])
    }
    $manualIdx = $found.Count + 1
    $skipIdx = $found.Count + 2
    Write-Host ("  [{0}] ввести путь вручную" -f $manualIdx)
    Write-Host ("  [{0}] пропустить ingest" -f $skipIdx)
    $choice = Read-Default "Номер выбора" "1"
    $n = 0
    if (-not [int]::TryParse($choice, [ref]$n)) {
        Write-Warning "Неверный выбор - ingest пропущен"
        return ""
    }
    if ($n -ge 1 -and $n -le $found.Count) {
        return $found[$n - 1]
    }
    if ($n -eq $manualIdx) {
        return Read-Default "Путь к bin платформы 1С (пусто = пропуск)" ""
    }
    return ""
}

function Ensure-SntxSem([hashtable]$EnvMap, [string[]]$PythonCmd) {
    Write-Step "1c-sntx-sem"
    $existing = Get-EnvOrMap $EnvMap "SNTX_SEM_CONFIG"
    $src = ""
    if ($existing -and (Test-Path -LiteralPath $existing -PathType Leaf)) {
        $src = Split-Path -Parent (Resolve-Path -LiteralPath $existing).Path
    }
    else {
        $parent = Split-Path -Parent $RepoRoot
        foreach ($c in @((Join-Path $parent "1c-sntx-sem"), (Join-Path $ToolsDir "1c-sntx-sem"))) {
            if (Test-Path -LiteralPath (Join-Path $c "pyproject.toml") -PathType Leaf) {
                $src = (Resolve-Path $c).Path
                break
            }
        }
    }
    if (-not $src) {
        if (-not (Test-Command "git")) {
            throw "git not found (needed to clone 1c-sntx-sem). https://github.com/gybson63/1c-sntx-sem"
        }
        $src = Join-Path $ToolsDir "1c-sntx-sem"
        Write-Host "Cloning 1c-sntx-sem -> $src"
        Invoke-NativeProcess -FilePath "git" -ArgumentList @("clone", "--depth", "1", "https://github.com/gybson63/1c-sntx-sem.git", $src) -FailMessage "git clone 1c-sntx-sem failed"
    }
    $venvPy = Join-Path $src ".venv\Scripts\python.exe"
    if (-not (Test-Path -LiteralPath $venvPy -PathType Leaf)) {
        Invoke-Python -PythonCmd $PythonCmd -PythonArgs @("-m", "venv", ".venv") -WorkDir $src
    }
    Invoke-Python -PythonCmd @($venvPy) -PythonArgs @("-m", "pip", "install", "-U", "pip")
    Invoke-Python -PythonCmd @($venvPy) -PythonArgs @("-m", "pip", "install", "-e", ".") -WorkDir $src
    $config = Join-Path $src "config.yaml"
    if (-not (Test-Path -LiteralPath $config -PathType Leaf)) {
        $example = Join-Path $src "config.yaml.example"
        if (-not (Test-Path -LiteralPath $example -PathType Leaf)) {
            throw "missing $example"
        }
        Copy-Item -LiteralPath $example -Destination $config
        Write-Host "Created $config from example. Edit local_configs / ingest as needed."
    }
    $doIngest = -not $SkipIngest
    $chosenPlatform = $PlatformPath
    if ($doIngest) {
        if (-not $chosenPlatform) {
            $chosenPlatform = Select-PlatformBinForIngest
        }
        if ([string]::IsNullOrWhiteSpace($chosenPlatform)) {
            Write-Warning "Skipping ingest: no platform path. sntx_sem search will not work until you run: $venvPy -m sntx_sem ingest --platform-path PLATFORM_BIN"
        }
        else {
            Invoke-Python -PythonCmd @($venvPy) -PythonArgs @("-m", "sntx_sem", "ingest", "--platform-path", $chosenPlatform) -WorkDir $src
        }
    }
    else {
        Write-Warning "Skipping ingest. Set SNTX_SEM_CONFIG and run ingest before a live eval."
    }
    return @{
        Config = (Resolve-Path $config).Path
        Python = (Resolve-Path $venvPy).Path
    }
}

function Resolve-JavaHome([hashtable]$EnvMap) {
    $existing = Get-EnvOrMap $EnvMap "JAVA_HOME"
    if ($existing -and (Test-Path -LiteralPath $existing -PathType Container)) {
        return (Resolve-Path $existing).Path
    }
    $java = Get-CommandPath "java"
    if (-not $java) {
        Write-Warning "Java not found (optional). Default BSL language-server MCP needs JDK 17+. docs/prerequisites.md"
        return ""
    }
    $oldEap = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $probe = & java -XshowSettings:properties -version 2>&1 | Select-String "java.home"
    }
    finally {
        $ErrorActionPreference = $oldEap
    }
    $detected = ""
    if ($probe) {
        $javaHomeDir = ($probe.ToString() -split "=", 2)[1].Trim()
        if (Test-Path -LiteralPath $javaHomeDir -PathType Container) {
            $detected = $javaHomeDir
        }
    }
    if ($NonInteractive -or -not $detected) {
        return $detected
    }
    Write-Hint ""
    Write-Hint "JAVA_HOME нужен штатному MCP bsl-language-server (анализ BSL). Можно оставить пустым, если свой MCP без Java."
    Write-Hint "Обнаружен Java home: $detected"
    return Read-Default "Путь JAVA_HOME" $detected
}

