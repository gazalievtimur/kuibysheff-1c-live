    [Environment]::SetEnvironmentVariable($name, $envMap[$name], "Process")
}

Save-DotEnv $envPath $envMap
Write-Host "Wrote $envPath"

Install-ConveyorProfiles $kbshff $RepoRoot $BaseUrl $Model $ApiKeyEnvName

